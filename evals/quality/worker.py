"""Run real services; save model-visible tool messages for public acceptance; keep auth/results."""

from __future__ import annotations

import importlib.util
import json
import os
import sys
from pathlib import Path


def main() -> None:
    service, port = sys.argv[1], int(sys.argv[2])
    if service == "retrieval":
        adapter = os.environ.get("QUALITY_CUDA_ADAPTER")
        if adapter:
            spec = importlib.util.spec_from_file_location("quality_cuda_execution", adapter)
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            runtime = module.enable_cuda(Path(os.environ["QUALITY_CUDA_PACKAGES"]))
            Path("retrieval-runtime.json").write_text(json.dumps(runtime), encoding="utf-8")
        from app.config import settings as service_settings

        from scripts.local_retrieval import app
    elif service == "ingestion":
        from app.config import settings as service_settings

        from scripts.local_ingestion import app
    elif service == "agent":
        from pydantic_ai.messages import (
            ModelRequest,
            ModelResponse,
            RetryPromptPart,
            ToolCallPart,
            ToolReturnPart,
        )

        from src.config import settings as service_settings
        from src.main import app
        from src.observability.tracer import tracer

        directory = Path("model-contexts")
        directory.mkdir(exist_ok=True)
        native_record = tracer.record

        def capture(trace, *, messages, **kwargs):
            returns = []
            requests = []
            output_retries = []
            model_calls = 0
            for message in messages:
                if isinstance(message, ModelResponse):
                    model_calls += 1
                    for part in message.parts:
                        if (
                            isinstance(part, ToolCallPart)
                            and part.tool_name == "search_knowledge_documents"
                        ):
                            try:
                                query = part.args_as_dict().get("query")
                            except ValueError:
                                query = None
                            requests.append({"call_id": part.tool_call_id, "query": query})
                if isinstance(message, ModelRequest):
                    for part in message.parts:
                        if (
                            isinstance(part, ToolReturnPart)
                            and part.tool_name == "search_knowledge_documents"
                        ):
                            returns.append({"call_id": part.tool_call_id, "content": part.content})
                        if isinstance(part, RetryPromptPart) and isinstance(part.content, str):
                            if part.content.startswith("Answer failed evidence checks:"):
                                output_retries.append(part.content)
            receipt = {
                "trace_id": trace.trace_id,
                "status": kwargs["status"],
                "model_calls": model_calls,
                "tool_returns": returns,
                "knowledge_requests": requests,
                "evidence_output_retries": output_retries,
                "rule_scores": kwargs.get("rule_scores", {}),
            }
            # Trace IDs are generated by the real API; hash before constructing
            # a filename so a request header cannot select an arbitrary path.
            import hashlib

            key = hashlib.sha256(trace.trace_id.encode()).hexdigest()
            (directory / (key + ".json")).write_text(
                json.dumps(receipt, ensure_ascii=False), encoding="utf-8"
            )
            return native_record(trace, messages=messages, **kwargs)

        tracer.record = capture
    else:
        raise ValueError("Unknown production service")
    actual = service_settings.model_dump(mode="json")
    from evals.quality.runtime import archive_source_epoch, source_fingerprint

    fingerprint = source_fingerprint()
    epoch = Path(f"{service}-source-{fingerprint['sha256']}")
    epoch.mkdir(exist_ok=True)
    if not (epoch / "loaded-source-epoch.zip").exists():
        archive_source_epoch(epoch, fingerprint)
    Path(service + "-runtime-source.json").write_text(
        json.dumps(
            {
                "pid": os.getpid(),
                "source": fingerprint,
                "source_archive": str(epoch / "loaded-source-epoch.zip"),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    filtered = {
        key: value
        for key, value in actual.items()
        if not any(part in key.lower() for part in ("api_key", "secret", "password", "auth_header"))
        and key.lower() != "token"
    }
    Path(service + "-effective-settings.json").write_text(
        json.dumps(filtered, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    import uvicorn

    uvicorn.run(app, host="127.0.0.1", port=port, log_level="warning")


if __name__ == "__main__":
    main()
