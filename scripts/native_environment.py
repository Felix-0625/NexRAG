def _webui_environment(
    common: dict,
    base: dict[str, str],
    ports: dict[str, int],
    root: Path,
    frontend_assets: Path,
    exports: Path,
) -> dict:
    # Upstream calls the slim-dependency flag USE_SLIM_DOCKER; native slim installs need it too,
    # but no container engine is invoked.
    webui = dict(
        common,
        USE_SLIM_DOCKER="true",
        NEXRAG_LOCAL_STT="true",
        WHISPER_COMPUTE_TYPE=base.get("WHISPER_COMPUTE_TYPE", "int8"),
        WHISPER_MODEL_DIR=str(root / ".local-run" / "cache" / "whisper"),
        WEBUI_AUTH="true",
        WEBUI_NAME="NexRAG",
        ENABLE_VERSION_UPDATE_CHECK="false",
        BYPASS_ADMIN_ACCESS_CONTROL="false",
        ENABLE_ADMIN_WORKSPACE_CONTENT_ACCESS="false",
        ENABLE_ADMIN_CHAT_ACCESS="false",
        ENABLE_ADMIN_EXPORT="false",
        ENABLE_PLUGINS="true"
        if base.get("NEXRAG_ALLOW_TRUSTED_PLUGINS", "").lower() == "true"
        else "false",
        DATA_DIR=str(root / "data/openwebui"),
        ENABLE_OLLAMA_API="false",
        STATIC_DIR=str(root / "data/openwebui/static"),
        FRONTEND_BUILD_DIR=str(frontend_assets),
        ENABLE_OPENAI_API="true",
        OPENAI_API_BASE_URL=url(ports["nexrag"]) + "/v1",
        OPENAI_API_KEY=base["NEXRAG_SHARED_API_KEY"],
        ENABLE_FORWARD_USER_INFO_HEADERS="true",
        FORWARD_USER_INFO_HEADER_JWT_SECRET=base["NEXRAG_USER_JWT_SECRET"],
        NEXRAG_API_BASE_URL=url(ports["nexrag"]) + "/v1",
        NEXRAG_EXPORTS_DIR=str(exports),
        CORS_ALLOW_ORIGIN=url(ports["web"]),
    )
    _apply_webui_feature_flags(webui)
    return webui


def _apply_webui_feature_flags(webui: dict) -> None:
    """Disable unneeded upstream features while enabling workspace capabilities."""
    for name in (
        "CHANNELS",
        "CALENDAR",
        "CODE_INTERPRETER",
        "MEMORIES",
        "GOOGLE_DRIVE_INTEGRATION",
        "ONEDRIVE_INTEGRATION",
        "EVALUATION_ARENA_MODELS",
        "WEB_SEARCH",
    ):
        webui[f"ENABLE_{name}"] = "false"
    webui.update(
        NEXRAG_WORKSPACE="true",
        ENABLE_NOTES="true",
        ENABLE_AUTOMATIONS="true",
        ENABLE_KNOWLEDGE_FILE_RETENTION="true",
        USER_PERMISSIONS_WORKSPACE_KNOWLEDGE_ACCESS="true",
        USER_PERMISSIONS_WORKSPACE_MODELS_ACCESS="true",
        USER_PERMISSIONS_WORKSPACE_SKILLS_ACCESS="true",
        USER_PERMISSIONS_WORKSPACE_TOOLS_ACCESS="true",
    )


def service_environments(
    base: dict[str, str], ports: dict[str, int], *, root: Path, state: Path, report
) -> dict[str, dict]:
    """Build isolated service environments, data directories, and frontend assets."""
    _ensure_data_folders(root)
    # Upstream refreshes STATIC_DIR from build/static at import, but Vite has no production build;
    # use an assets-only directory so backend/static in the checkout is not cleared.
    frontend_assets = state / "webui-assets"
    _sync_frontend_assets(root, frontend_assets)
    common, exports = _common_environment(base, ports, root)
    ingestion = _ingestion_environment(common, base, root)
    retrieval = _retrieval_environment(common, base, root)
    webui = _webui_environment(common, base, ports, root, frontend_assets, exports)
    # Enable internet search only when a real SearXNG endpoint exists.
    if base.get("ENABLE_WEB_SEARCH", "").lower() == "true":
        report(
            "Optional web search requested; the workspace tools page shows its configuration status."
        )
    return {
        "nexrag": common,
        "retrieval": retrieval,
        "ingestion": ingestion,
        "webui": webui,
        "frontend": dict(common, WEBUI_BACKEND_URL=url(ports["webui"])),
    }
